#[test]
fn credentials_move_outside_workspace_with_restricted_permissions() {
    let runner_temp = TempDir::new().value();
    let workspace = TempDir::new().value();
    let source = workspace.path().join("credentials.json");
    fs::write(&source, "{\"fixture\":true}").value();
    let output_path = runner_temp.path().join("outputs");
    let environment_path = runner_temp.path().join("environment");
    let output = invoke(
        "credentials",
        workspace.path(),
        &[
            ("CREDENTIALS_FILE", source.to_str().value()),
            ("RUNNER_TEMP", runner_temp.path().to_str().value()),
            ("GITHUB_OUTPUT", output_path.to_str().value()),
            ("GITHUB_ENV", environment_path.to_str().value()),
        ],
    );
    assert!(
        output.status.success(),
        "{}",
        String::from_utf8_lossy(&output.stderr)
    );
    let outputs = fs::read_to_string(output_path).value();
    let path = outputs.trim().strip_prefix("path=").value();
    let destination = Path::new(path);
    assert!(destination.starts_with(runner_temp.path().canonicalize().value()));
    #[cfg(unix)]
    assert_eq!(
        fs::metadata(destination).value().permissions().mode() & 0o777,
        0o600
    );
    assert!(!source.exists());
    let environment = fs::read_to_string(environment_path).value();
    assert!(environment.contains(&format!("GOOGLE_APPLICATION_CREDENTIALS={path}")));
    assert!(environment.contains(&format!("CLOUDSDK_AUTH_CREDENTIAL_FILE_OVERRIDE={path}")));
    assert!(environment.contains(&format!("GOOGLE_GHA_CREDS_PATH={path}")));
}

