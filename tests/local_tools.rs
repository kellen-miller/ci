#[test]
fn real_golangci_formatter_reports_diffs_without_rewriting_sources() {
    if Command::new("golangci-lint")
        .arg("--version")
        .output()
        .is_err()
    {
        return;
    }
    let project = TempDir::new().value();
    fs::write(
        project.path().join("go.mod"),
        "module example.com/fixture\n\ngo 1.24\n",
    )
    .value();
    let config = project.path().join(".golangci.yaml");
    fs::write(
        &config,
        "version: \"2\"\nformatters:\n  enable:\n    - gofmt\n  settings:\n    gofmt:\n      rewrite-rules:\n        - pattern: interface{}\n          replacement: any\n",
    )
    .value();
    let source = project.path().join("main.go");
    let original = "package main\n\nfunc main() {\n\tvar value interface{}\n\tprintln(value)\n}\n";
    fs::write(&source, original).value();
    let failed = invoke(
        "go-format",
        project.path(),
        &[("LINT_CONFIG", ".golangci.yaml")],
    );
    assert!(!failed.status.success());
    assert!(String::from_utf8_lossy(&failed.stdout).contains("any"));
    assert_eq!(fs::read_to_string(&source).value(), original);
    let format = Command::new("gofmt")
        .args(["-w", "-r", "interface{} -> any", "main.go"])
        .current_dir(project.path())
        .status()
        .value();
    assert!(format.success());
    let success = invoke(
        "go-format",
        project.path(),
        &[("LINT_CONFIG", ".golangci.yaml")],
    );
    assert!(
        success.status.success(),
        "{}",
        String::from_utf8_lossy(&success.stdout)
    );
}

