trait FixtureValue<T> {
    fn value(self) -> T;
}

impl<T, E: std::fmt::Debug> FixtureValue<T> for Result<T, E> {
    fn value(self) -> T {
        match self {
            Ok(value) => value,
            Err(error) => panic!("fixture setup failed: {error:?}"),
        }
    }
}

impl<T> FixtureValue<T> for Option<T> {
    fn value(self) -> T {
        match self {
            Some(value) => value,
            None => panic!("fixture setup returned no value"),
        }
    }
}

fn invoke(operation: &str, directory: &Path, variables: &[(&str, &str)]) -> Output {
    let mut command = Command::new(env::current_exe().value());
    command
        .args(["--exact", "fixture_entry", "--nocapture"])
        .current_dir(directory)
        .env("LOCAL_TOOLS_FIXTURE", operation);
    for (name, value) in variables {
        command.env(name, value);
    }
    command.output().value()
}

fn recorder(directory: &TempDir, name: &str) -> String {
    let source =
        Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/local_tools_recorder.rs");
    let executable = directory.path().join(name);
    let status = Command::new("rustc")
        .args(["--edition=2024"])
        .arg(source)
        .arg("-o")
        .arg(&executable)
        .status()
        .value();
    assert!(status.success());
    executable.to_string_lossy().into_owned()
}

#[test]
fn fixture_entry() {
    let Ok(operation) = env::var("LOCAL_TOOLS_FIXTURE") else {
        return;
    };
    let result = match operation.as_str() {
        "clean" => personal_ci::local_files::run("clean-generated-output"),
        "credentials" => personal_ci::local_files::run("isolate-credentials"),
        "go-config" => personal_ci::local_files::run("go-config-output"),
        "go-format" => personal_ci::local_files::run("go-format"),
        "node" => personal_ci::node::run("detect"),
        "node-install" => personal_ci::node::run("install"),
        "cpd" => personal_ci::tooling::run("code-duplication"),
        "docker-cache" => personal_ci::tooling::run("docker-cache"),
        "playwright" => personal_ci::tooling::run("playwright-version"),
        "go-test" => personal_ci::tooling::run("go-test"),
        "gradle" => personal_ci::tooling::run("gradle-check"),
        "helm" => personal_ci::helm::run("lint"),
        _ => panic!("unknown fixture operation"),
    };
    if let Err(error) = result {
        panic!("local tools operation failed: {error:#}");
    }
}

#[test]
fn cleanup_removes_marked_files_and_preserves_links() {
    let workspace = TempDir::new().value();
    let target = workspace.path().join("generated");
    fs::create_dir_all(&target).value();
    fs::write(
        target.join("generated.go"),
        "// Generated by fixture; DO NOT EDIT.\n",
    )
    .value();
    fs::write(target.join("manual.go"), "// handwritten\n").value();
    let outside = workspace.path().join("outside.go");
    fs::write(&outside, "// Generated by fixture; DO NOT EDIT.\n").value();
    #[cfg(unix)]
    std::os::unix::fs::symlink(&outside, target.join("linked.go")).value();
    let output = invoke(
        "clean",
        workspace.path(),
        &[
            ("GITHUB_WORKSPACE", workspace.path().to_str().value()),
            ("WORKING_DIRECTORY", "generated"),
        ],
    );
    assert!(
        output.status.success(),
        "{}",
        String::from_utf8_lossy(&output.stderr)
    );
    assert!(!target.join("generated.go").exists());
    assert!(target.join("manual.go").exists());
    assert!(outside.exists());
    let root_cleanup = invoke(
        "clean",
        workspace.path(),
        &[
            ("GITHUB_WORKSPACE", workspace.path().to_str().value()),
            ("WORKING_DIRECTORY", "."),
        ],
    );
    assert!(!root_cleanup.status.success());
}

