#[test]
fn real_npm_ci_keeps_a_frozen_lockfile_on_failure() {
    if Command::new("npm").arg("--version").output().is_err() {
        return;
    }
    let project = TempDir::new().value();
    fs::write(
        project.path().join("package.json"),
        "{\"name\":\"fixture\",\"version\":\"1.0.0\"}\n",
    )
    .value();
    let lock = Command::new("npm")
        .args([
            "install",
            "--package-lock-only",
            "--ignore-scripts",
            "--no-audit",
        ])
        .current_dir(project.path())
        .status()
        .value();
    assert!(lock.success());
    let lockfile = project.path().join("package-lock.json");
    let original = fs::read(&lockfile).value();
    let success = invoke("node-install", project.path(), &[("PM", "npm")]);
    assert!(
        success.status.success(),
        "{}",
        String::from_utf8_lossy(&success.stderr)
    );
    fs::write(
        project.path().join("package.json"),
        "{\"name\":\"fixture\",\"version\":\"1.0.0\",\"dependencies\":{\"missing\":\"file:absent\"}}\n",
    )
    .value();
    let failure = invoke("node-install", project.path(), &[("PM", "npm")]);
    assert!(!failure.status.success());
    assert_eq!(fs::read(lockfile).value(), original);
}

