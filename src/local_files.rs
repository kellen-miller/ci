//! Filesystem and Go formatting operations used by composite actions.

use std::env;
use std::fs;
#[cfg(unix)]
use std::os::unix::fs::PermissionsExt;
use std::path::PathBuf;
use std::process::Command;

use anyhow::{Context, Result, bail, ensure};

use crate::github_output;

/// Run one filesystem or Go formatting operation.
///
/// # Errors
/// Returns an error for unsupported operations, invalid inputs, failed child processes, or filesystem errors.
pub fn run(operation: &str) -> Result<()> {
    match operation {
        "clean-generated-output" => clean_generated_output(),
        "isolate-credentials" => isolate_credentials(),
        "go-config" => go_config(false),
        "go-config-output" => go_config(true),
        "go-format" => go_format(),
        _ => bail!("unknown local-files operation: {operation}"),
    }
}

fn clean_generated_output() -> Result<()> {
    let workspace = PathBuf::from(env::var("GITHUB_WORKSPACE")?)
        .canonicalize()
        .context("resolve GITHUB_WORKSPACE")?;
    let requested = workspace.join(env::var("WORKING_DIRECTORY")?);
    let target = requested
        .canonicalize()
        .with_context(|| format!("resolve working directory {}", requested.display()))?;
    ensure!(
        target != workspace && target.starts_with(&workspace),
        "Select a directory strictly inside GITHUB_WORKSPACE"
    );
    ensure!(
        target.is_dir(),
        "Directory does not exist: {}",
        target.display()
    );

    let mut directories = walkdir::WalkDir::new(&target)
        .follow_links(false)
        .contents_first(true)
        .into_iter()
        .collect::<std::result::Result<Vec<_>, _>>()?;
    directories.sort_by_key(|entry| std::cmp::Reverse(entry.depth()));
    let generated = regex::bytes::Regex::new(r"generated by[^\r\n]*do not edit")?;
    for entry in directories {
        let path = entry.path();
        let metadata = fs::symlink_metadata(path)?;
        if metadata.file_type().is_symlink() {
            continue;
        }

        if metadata.is_file() {
            let mut file = fs::File::open(path)?;
            let mut header = Vec::new();
            use std::io::{BufRead, BufReader};
            let mut reader = BufReader::new(&mut file);
            for _ in 0..10 {
                let mut line = Vec::new();
                if reader.read_until(b'\n', &mut line)? == 0 {
                    break;
                }

                header.extend(line);
            }

            let lowered = header
                .iter()
                .map(u8::to_ascii_lowercase)
                .collect::<Vec<_>>();
            if generated.is_match(&lowered) {
                println!(
                    "Removing generated file: {}",
                    path.strip_prefix(&workspace)?.display()
                );
                fs::remove_file(path)?;
            }
        } else if metadata.is_dir() && path != target && fs::read_dir(path)?.next().is_none() {
            fs::remove_dir(path)?;
        }
    }

    Ok(())
}

fn isolate_credentials() -> Result<()> {
    let source = PathBuf::from(env::var("CREDENTIALS_FILE")?);
    let runner_temp = PathBuf::from(env::var("RUNNER_TEMP")?);
    let directory = tempfile::Builder::new()
        .prefix("cloud-credentials-")
        .tempdir_in(&runner_temp)?;
    let destination = directory.path().join("credentials.json");
    match fs::rename(&source, &destination) {
        Ok(()) => {}
        Err(error) if is_cross_device(&error) => {
            fs::copy(&source, &destination)?;
            fs::remove_file(&source)?;
        }

        Err(error) => return Err(error.into()),
    }

    set_private_permissions(&destination)?;
    let destination = destination.canonicalize()?;
    let _persistent_directory = directory.keep();
    let path_value = destination.to_string_lossy();
    let env_path = PathBuf::from(env::var("GITHUB_ENV")?);
    for name in [
        "GOOGLE_APPLICATION_CREDENTIALS",
        "CLOUDSDK_AUTH_CREDENTIAL_FILE_OVERRIDE",
        "GOOGLE_GHA_CREDS_PATH",
    ] {
        github_output::write(&env_path, name, &path_value)?;
    }

    github_output::append("path", &path_value)
}

fn is_cross_device(error: &std::io::Error) -> bool {
    #[cfg(unix)]
    {
        error.raw_os_error() == Some(18)
    }

    #[cfg(windows)]
    {
        error.raw_os_error() == Some(17)
    }

    #[cfg(not(any(unix, windows)))]
    {
        let _ = error;
        false
    }
}

#[cfg(unix)]
fn set_private_permissions(path: &PathBuf) -> Result<()> {
    fs::set_permissions(path, fs::Permissions::from_mode(0o600))?;
    Ok(())
}

#[cfg(not(unix))]
fn set_private_permissions(_path: &PathBuf) -> Result<()> {
    bail!("setting credential permissions to 0600 is unsupported on this platform")
}

fn go_config(write_output: bool) -> Result<()> {
    let path = resolve_go_config()?;
    let rendered = path.to_string_lossy();
    println!("{}", path.display());
    if write_output {
        let args = format!("--config {}", shell_quote(&rendered)?);
        github_output::append("args", &args)?;
    }

    Ok(())
}

fn go_format() -> Result<()> {
    let path = resolve_go_config()?;
    let output = Command::new("golangci-lint")
        .args(["fmt", "--diff", "--config"])
        .arg(path)
        .output()
        .context("execute golangci-lint fmt")?;
    use std::io::Write;
    std::io::stdout().write_all(&output.stdout)?;
    std::io::stderr().write_all(&output.stderr)?;
    if !output.status.success() || !output.stdout.is_empty() {
        bail!("Go formatting check failed");
    }

    Ok(())
}

fn resolve_go_config() -> Result<PathBuf> {
    let configured = env::var("LINT_CONFIG").unwrap_or_default();
    ensure!(
        !configured.contains(['\n', '\r']),
        "config must be a single-line path"
    );
    let path = if configured.is_empty() {
        let root = env::var_os("CI_ROOT")
            .map(PathBuf::from)
            .unwrap_or_else(|| PathBuf::from(env!("CARGO_MANIFEST_DIR")));
        root.join("config/golangci.yaml")
    } else {
        PathBuf::from(configured)
    };

    ensure!(
        path.is_file(),
        "config file does not exist: {}",
        path.display()
    );
    let path = path.canonicalize().context("resolve lint config path")?;
    ensure!(
        !path.to_string_lossy().contains(['\n', '\r']),
        "config must be a single-line path"
    );
    ensure!(
        path.is_file(),
        "config file does not exist: {}",
        path.display()
    );
    Ok(path)
}

fn shell_quote(value: &str) -> Result<String> {
    ensure!(
        !value.contains(['\n', '\r']),
        "config must be a single-line path"
    );
    Ok(format!("'{}'", value.replace('\'', "'\\''")))
}
